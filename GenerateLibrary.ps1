$ErrorActionPreference = 'Stop'
Add-Type -TypeDefinition @'
using System;
using System.IO;
public static class MaliMp3Duration {
    static readonly int[] V1={0,32,40,48,56,64,80,96,112,128,160,192,224,256,320,0};
    static readonly int[] V2={0,8,16,24,32,40,48,56,64,80,96,112,128,144,160,0};
    static bool Header(byte[] b,int p,out int length,out double seconds) {
        length=0; seconds=0;
        if(p+4>b.Length || b[p]!=255 || (b[p+1]&224)!=224) return false;
        int v=(b[p+1]>>3)&3, layer=(b[p+1]>>1)&3;
        int bi=(b[p+2]>>4)&15, si=(b[p+2]>>2)&3;
        if(v==1 || layer!=1 || bi==0 || bi==15 || si==3) return false;
        int rate=new int[]{44100,48000,32000}[si];
        if(v==2) rate/=2; else if(v==0) rate/=4;
        int bitrate=(v==3?V1[bi]:V2[bi])*1000;
        length=(v==3?144:72)*bitrate/rate+((b[p+2]>>1)&1);
        seconds=(double)(v==3?1152:576)/rate;
        return length>=4;
    }
    public static double Read(string path) {
        byte[] b=File.ReadAllBytes(path);
        int p=0;
        if(b.Length>=10 && b[0]==73 && b[1]==68 && b[2]==51) {
            p=10+(((b[6]&127)<<21)|((b[7]&127)<<14)|((b[8]&127)<<7)|(b[9]&127));
            if(b[3]==4 && (b[5]&16)!=0) p+=10;
        }
        double total=0; int frames=0; bool locked=false;
        while(p+4<=b.Length) {
            int len; double sec;
            if(Header(b,p,out len,out sec) && (long)p+len<=b.Length) {
                if(!locked) {
                    int next; double unused;
                    if(p+len+4>b.Length || !Header(b,p+len,out next,out unused)) { p++; continue; }
                }
                total+=sec; frames++; p+=len; locked=true;
            } else { locked=false; p++; }
        }
        return frames>=2?total:0;
    }
}
'@
function LuaString([string]$s) {
    $s=$s.Replace('\','\\').Replace('"','\"').Replace("`r",'\r').Replace("`n",'\n').Replace("`t",'\t')
    return '"'+$s+'"'
}
$music=Join-Path $PSScriptRoot 'mp3'
if (!(Test-Path -LiteralPath $music)) { New-Item -ItemType Directory -Path $music | Out-Null }
$files=@(Get-ChildItem -LiteralPath $music -Filter '*.mp3' -File -Recurse | Sort-Object FullName)
$lines=New-Object 'System.Collections.Generic.List[string]'
$lines.Add('-- Generated by MaliMusicPlayer 0.4; durations scanned from MP3 frames.')
$lines.Add('MaliMusicPlayerLibrary = {')
$shell=$null
try { $shell=New-Object -ComObject Shell.Application } catch { Write-Warning 'Optional Windows tags unavailable; using filenames.' }
$failures=New-Object 'System.Collections.Generic.List[string]'
$i=0
try {
    foreach($file in $files) {
        $i++
        Write-Progress -Activity 'Generating MaliMusicPlayer library' -Status $file.Name -PercentComplete (100*$i/[Math]::Max(1,$files.Count))
        $title=$file.BaseName; $artist=''; $duration=0.0
        if($shell) {
            try {
                $folder=$shell.NameSpace($file.DirectoryName); $item=$folder.ParseName($file.Name)
                $tag=$folder.GetDetailsEx($item,'System.Title')
                if($tag -is [string] -and $tag.Trim()) { $title=$tag }
                $tag=$folder.GetDetailsEx($item,'System.Music.Artist')
                if($tag) { $artist=@($tag) -join ', ' }
            } catch { }
        }
        try { $duration=[MaliMp3Duration]::Read($file.FullName) } catch { Write-Warning $_.Exception.Message }
        if($duration -le 0) { $failures.Add($file.FullName) }
        $relative=$file.FullName.Substring($PSScriptRoot.Length+1).Replace('\','/')
        $path='Interface/AddOns/MaliMusicPlayer/'+$relative
        $d=$duration.ToString('0.###',[Globalization.CultureInfo]::InvariantCulture)
        $lines.Add(('  {{ title={0}, artist={1}, path={2}, duration={3} }},' -f (LuaString $title),(LuaString $artist),(LuaString $path),$d))
    }
    $lines.Add('}')
    $temp=Join-Path $PSScriptRoot 'Library.lua.tmp'
    [IO.File]::WriteAllLines($temp,$lines,(New-Object System.Text.UTF8Encoding($false)))
    Move-Item -LiteralPath $temp -Destination (Join-Path $PSScriptRoot 'Library.lua') -Force
} finally {
    Write-Progress -Activity 'Generating MaliMusicPlayer library' -Completed
    if($shell) { [void][Runtime.InteropServices.Marshal]::ReleaseComObject($shell) }
}
Write-Host ("Found: {0} MP3s; durations detected: {1}; failed: {2}" -f $files.Count,($files.Count-$failures.Count),$failures.Count)
foreach($bad in $failures) { Write-Warning "No duration: $bad" }
Write-Host 'Library rebuilt. Restart WoW after adding audio; /reload is enough for duration/title changes.'
